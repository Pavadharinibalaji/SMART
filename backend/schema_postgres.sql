-- ==============================================================================
-- SMART Academic Intelligence Platform - Supabase PostgreSQL Schema
-- Idempotent schema definition reproducing all 24 SMART SQLite tables.
-- ==============================================================================

-- 1. Users and Authentication
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    role TEXT NOT NULL CHECK(role IN ('student', 'teacher')),
    status TEXT NOT NULL DEFAULT 'active',
    picture TEXT,
    is_demo INTEGER DEFAULT 0,
    department TEXT,
    program TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);

-- 2. User Sessions
CREATE TABLE IF NOT EXISTS user_sessions (
    id TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    csrf_token TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_user_sessions_user ON user_sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_user_sessions_expires ON user_sessions(expires_at);

-- 3. SMART Courses
CREATE TABLE IF NOT EXISTS smart_courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    teacher_name TEXT,
    teacher_email TEXT,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    section TEXT,
    description TEXT,
    join_code TEXT NOT NULL UNIQUE,
    is_active INTEGER NOT NULL DEFAULT 1,
    theme_color TEXT DEFAULT '#6366f1',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_smart_courses_teacher ON smart_courses(teacher_id);
CREATE INDEX IF NOT EXISTS idx_smart_courses_join_code ON smart_courses(join_code);

-- 4. Course Memberships
CREATE TABLE IF NOT EXISTS course_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES smart_courses(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role TEXT NOT NULL CHECK(role IN ('teacher', 'student', 'ta')),
    status TEXT NOT NULL DEFAULT 'enrolled' CHECK(status IN ('enrolled', 'dropped', 'pending_approval')),
    joined_at TEXT NOT NULL,
    UNIQUE (course_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_course_memberships_course ON course_memberships(course_id);
CREATE INDEX IF NOT EXISTS idx_course_memberships_user ON course_memberships(user_id);

-- 5. Course Invitations
CREATE TABLE IF NOT EXISTS course_invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES smart_courses(id) ON DELETE CASCADE,
    inviter_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    student_email TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending', 'accepted', 'revoked')),
    created_at TEXT NOT NULL,
    responded_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_course_invitations_email ON course_invitations(student_email);

-- 6. Course Announcements
CREATE TABLE IF NOT EXISTS course_announcements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES smart_courses(id) ON DELETE CASCADE,
    teacher_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    content TEXT NOT NULL,
    is_pinned INTEGER NOT NULL DEFAULT 0,
    target_student_ids TEXT,
    attachment_urls TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_course_announcements_course ON course_announcements(course_id);

-- 7. Announcement Read Receipts
CREATE TABLE IF NOT EXISTS announcement_read_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id BIGINT NOT NULL REFERENCES course_announcements(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    acknowledged_at TEXT NOT NULL,
    UNIQUE (announcement_id, student_id)
);

-- 8. Course Messages
CREATE TABLE IF NOT EXISTS course_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES smart_courses(id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    recipient_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    content TEXT NOT NULL,
    attachment_url TEXT,
    attachment_name TEXT,
    is_edited INTEGER NOT NULL DEFAULT 0,
    is_deleted INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_course_messages_course ON course_messages(course_id);

-- 9. Message Read Receipts
CREATE TABLE IF NOT EXISTS message_read_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT NOT NULL REFERENCES course_messages(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    read_at TEXT NOT NULL,
    UNIQUE (message_id, user_id)
);

-- 10. Course Polls
CREATE TABLE IF NOT EXISTS course_polls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES smart_courses(id) ON DELETE CASCADE,
    creator_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    question TEXT NOT NULL,
    poll_type TEXT NOT NULL DEFAULT 'multiple_choice' CHECK(poll_type IN ('multiple_choice', 'yes_no', 'feedback', 'short_feedback')),
    is_anonymous INTEGER NOT NULL DEFAULT 0,
    results_visible_before_close INTEGER NOT NULL DEFAULT 1,
    is_closed INTEGER NOT NULL DEFAULT 0,
    closes_at TEXT,
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_course_polls_course ON course_polls(course_id);

-- 11. Poll Options
CREATE TABLE IF NOT EXISTS poll_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poll_id BIGINT NOT NULL REFERENCES course_polls(id) ON DELETE CASCADE,
    option_text TEXT NOT NULL,
    display_order INTEGER NOT NULL DEFAULT 0
);

-- 12. Poll Votes
CREATE TABLE IF NOT EXISTS poll_votes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poll_id BIGINT NOT NULL REFERENCES course_polls(id) ON DELETE CASCADE,
    option_id BIGINT REFERENCES poll_options(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    feedback_text TEXT,
    created_at TEXT NOT NULL,
    UNIQUE (poll_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_poll_votes_poll ON poll_votes(poll_id);

-- 13. Notifications
CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    course_id BIGINT REFERENCES smart_courses(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    notification_type TEXT NOT NULL CHECK(notification_type IN ('announcement', 'poll', 'message', 'invitation', 'enrollment', 'submission_graded', 'deadline_approaching', 'task')),
    reference_id TEXT,
    is_read INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_notifications_user ON notifications(user_id, is_read);

-- 14. Course Materials
CREATE TABLE IF NOT EXISTS course_materials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES smart_courses(id) ON DELETE CASCADE,
    uploaded_by BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    description TEXT,
    original_filename TEXT NOT NULL,
    stored_filename TEXT NOT NULL,
    storage_path TEXT NOT NULL,
    file_extension TEXT NOT NULL,
    mime_type TEXT NOT NULL,
    file_size INTEGER NOT NULL,
    category TEXT NOT NULL DEFAULT 'Study Materials',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_course_materials_uploader ON course_materials(uploaded_by);
CREATE INDEX IF NOT EXISTS idx_course_materials_category ON course_materials(category);
CREATE INDEX IF NOT EXISTS idx_course_materials_course ON course_materials(course_id);

-- 15. Academic Items (WhatsApp extracted tasks)
CREATE TABLE IF NOT EXISTS academic_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT NOT NULL,
    description TEXT,
    date_text TEXT,
    due_date TEXT,
    date_type TEXT,
    date_status TEXT,
    status TEXT NOT NULL DEFAULT 'pending',
    source_sender TEXT,
    source_timestamp TEXT,
    source_text TEXT NOT NULL,
    source_filename TEXT,
    source_type TEXT DEFAULT 'whatsapp',
    source_id TEXT,
    source_metadata TEXT,
    review_required INTEGER NOT NULL DEFAULT 0,
    review_reasons TEXT,
    evidence_text TEXT,
    evidence_start_index INTEGER,
    evidence_end_index INTEGER,
    confidence TEXT DEFAULT 'MEDIUM',
    confidence_reasons TEXT,
    is_actionable INTEGER,
    actionability_type TEXT,
    update_type TEXT,
    is_range INTEGER DEFAULT 0,
    previous_due_date TEXT,
    replaces_task_id BIGINT,
    importance TEXT DEFAULT 'UNASSESSED',
    academic_intent TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_academic_items_source ON academic_items(source_type, source_id);
CREATE INDEX IF NOT EXISTS idx_academic_items_dedup ON academic_items(source_text, source_timestamp, source_sender, category);
CREATE INDEX IF NOT EXISTS idx_academic_items_confidence ON academic_items(confidence);
CREATE INDEX IF NOT EXISTS idx_academic_items_due_date ON academic_items(due_date);
CREATE INDEX IF NOT EXISTS idx_academic_items_status ON academic_items(status);
CREATE INDEX IF NOT EXISTS idx_academic_items_category ON academic_items(category);

-- 16. Opportunities (Competitions, Hackathons, Scholarships)
CREATE TABLE IF NOT EXISTS opportunities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    organizer TEXT,
    description TEXT,
    eligibility TEXT,
    registration_deadline TEXT,
    event_date TEXT,
    registration_url TEXT,
    source_type TEXT DEFAULT 'gmail',
    source_id TEXT,
    source_sender TEXT,
    source_timestamp TEXT,
    evidence_text TEXT,
    confidence TEXT DEFAULT 'HIGH',
    review_status TEXT DEFAULT 'confirmed',
    is_demo INTEGER DEFAULT 0,
    category TEXT DEFAULT 'Competition',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_opportunities_source ON opportunities(source_type, source_id);
CREATE INDEX IF NOT EXISTS idx_opportunities_deadline ON opportunities(registration_deadline);

-- 17. Student Opportunity Statuses (Legacy participation)
CREATE TABLE IF NOT EXISTS student_opportunity_statuses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id TEXT NOT NULL,
    opportunity_id BIGINT NOT NULL REFERENCES opportunities(id) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'discovered',
    evidence_notes TEXT,
    confirmation_source_ref TEXT,
    updated_by TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    UNIQUE (student_id, opportunity_id)
);
CREATE INDEX IF NOT EXISTS idx_student_opp_status ON student_opportunity_statuses(student_id, status);

-- 18. Student Tracked Opportunities (SMART 3.2 Native Tracker)
CREATE TABLE IF NOT EXISTS student_tracked_opportunities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    opportunity_id BIGINT REFERENCES opportunities(id) ON DELETE SET NULL,
    course_id BIGINT REFERENCES smart_courses(id) ON DELETE SET NULL,
    title TEXT NOT NULL,
    organizer TEXT,
    category TEXT NOT NULL DEFAULT 'Competition',
    description TEXT,
    registration_url TEXT,
    registration_deadline TEXT,
    event_date TEXT,
    tracking_status TEXT NOT NULL DEFAULT 'Interested',
    source_platform TEXT DEFAULT 'manual',
    source_reference TEXT,
    reminders_sent TEXT DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_student_tracked_opps_status ON student_tracked_opportunities(tracking_status);
CREATE INDEX IF NOT EXISTS idx_student_tracked_opps_deadline ON student_tracked_opportunities(registration_deadline);
CREATE INDEX IF NOT EXISTS idx_student_tracked_opps_course ON student_tracked_opportunities(course_id);
CREATE INDEX IF NOT EXISTS idx_student_tracked_opps_student ON student_tracked_opportunities(student_id);

-- 19. Google Accounts
CREATE TABLE IF NOT EXISTS google_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    name TEXT,
    picture TEXT,
    encrypted_access_token TEXT,
    encrypted_refresh_token TEXT,
    token_expiry TEXT,
    scopes TEXT,
    role TEXT DEFAULT 'student',
    is_demo INTEGER DEFAULT 0,
    last_sync_gmail TEXT,
    last_sync_classroom TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

-- 20. Google Classroom Courses
CREATE TABLE IF NOT EXISTS classroom_courses (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    section TEXT,
    description_heading TEXT,
    room TEXT,
    owner_id TEXT,
    teacher_email TEXT,
    user_role TEXT DEFAULT 'student',
    alternate_link TEXT,
    is_demo INTEGER DEFAULT 0,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

-- 21. Google Classroom Coursework
CREATE TABLE IF NOT EXISTS classroom_coursework (
    id TEXT PRIMARY KEY,
    course_id TEXT NOT NULL REFERENCES classroom_courses(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    description TEXT,
    due_date TEXT,
    due_time TEXT,
    max_points REAL,
    work_type TEXT DEFAULT 'ASSIGNMENT',
    state TEXT DEFAULT 'PUBLISHED',
    alternate_link TEXT,
    is_demo INTEGER DEFAULT 0,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_classroom_coursework_course ON classroom_coursework(course_id);

-- 22. Google Classroom Submissions
CREATE TABLE IF NOT EXISTS classroom_submissions (
    id TEXT PRIMARY KEY,
    course_id TEXT NOT NULL,
    coursework_id TEXT NOT NULL REFERENCES classroom_coursework(id) ON DELETE CASCADE,
    student_id TEXT NOT NULL,
    student_name TEXT,
    state TEXT NOT NULL DEFAULT 'NEW',
    assigned_grade REAL,
    late INTEGER DEFAULT 0,
    alternate_link TEXT,
    is_demo INTEGER DEFAULT 0,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_classroom_submissions_student ON classroom_submissions(student_id);
CREATE INDEX IF NOT EXISTS idx_classroom_submissions_cw ON classroom_submissions(coursework_id);

-- 23. Study Materials (Ingested resources)
CREATE TABLE IF NOT EXISTS study_materials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    file_name TEXT NOT NULL,
    file_type TEXT,
    file_size INTEGER,
    file_url TEXT,
    source_type TEXT NOT NULL,
    source_id TEXT,
    course_id TEXT,
    course_name TEXT,
    uploaded_by TEXT,
    is_demo INTEGER DEFAULT 0,
    description TEXT,
    resource_type TEXT DEFAULT 'file',
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_study_materials_course ON study_materials(course_id);

-- 24. Schema Migrations Log
CREATE TABLE IF NOT EXISTS schema_migrations (
    migration_name TEXT PRIMARY KEY,
    applied_at TEXT NOT NULL
);
